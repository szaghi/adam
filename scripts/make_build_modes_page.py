#!/usr/bin/env python3
"""Write the build-modes reference page (docs/reference/build-modes.md) from the modes the fobos file defines.

Why this script exists: the build modes live in the fobos files (`fobos`, `fobos.d/*.fobos`) and change with the code;
a hand-written list goes stale (the docs audit of issue #60 found 38 references to modes that did not exist). The page
is generated from `fobis build --lmodes`, so it lists exactly the modes FoBiS knows, and CI regenerates it before every
docs build. Each mode is classified from its name: the target (an application, the library, a test, a benchmark), the
backend and the variant suffixes. Standard library only.

Usage:
    make_build_modes_page.py [--fobos FILE] [--out FILE]     (defaults: fobos, docs/reference/build-modes.md)
"""

from __future__ import annotations

import argparse
import re
import subprocess
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Applications: name -> (display name, status). Every other first token is the library, a test or a benchmark.
APPS = {
    "flume": ("FLUME", "maintained"),
    "prism": ("PRISM", "maintained"),
    "ripple": ("RIPPLE", "maintained (the tutorial's toy app)"),
    "ascot": ("ASCOT", "utility, not maintained"),
    "nasto": ("NASTO", "not maintained"),
    "chase": ("CHASE", "does not build (superseded by FLUME)"),
    "patch": ("PATCH", "does not build"),
}

# Variant suffixes and what they add.
VARIANTS = {
    "debug": "debug flags",
    "omp": "CPU OpenMP threads",
    "fft": "links the FFT library of the self-gravity solvers (FFTW, cuFFT on nvfortran)",
    "cov": "coverage instrumentation",
    "spacehpc": "the `spacehpc` machine's flags",
}


@dataclass
class Mode:
    """A build mode and its classification."""

    name: str
    group: str
    backend: str
    compiler: str
    variants: list[str]


def list_modes(fobos: Path) -> list[str]:
    """Return the mode names `fobis build --lmodes` prints for a fobos file, in their fobos order."""
    cmd = ["fobis", "build", "--lmodes"]
    if fobos.name != "fobos" or fobos.resolve().parent != ROOT:
        cmd += ["-f", str(fobos)]
    out = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, check=True).stdout
    out = re.sub(r"\x1b\[[0-9;]*m", "", out)
    return re.findall(r'^\s*-\s*"([^"]+)"', out, flags=re.MULTILINE)


def classify(name: str) -> Mode:
    """Classify a mode by its name: its group, its backend and its variant suffixes."""
    first = name.split("-", 1)[0]
    if first in APPS:
        group = APPS[first][0]
    elif name.startswith("adam-com"):
        group = "Library"
    elif first == "bench":
        group = "Benchmarks"
    else:
        group = "Tests"
    compiler = "nvfortran" if "nvf" in name else "amdflang" if "amd" in name else "gfortran"
    if group == "Library":  # the common library alone, no backend macro
        backend = f"common library ({compiler})"
    elif "nvf-cuda" in name:
        backend = "CUDA Fortran (nvfortran)"
    elif "cpu-" in name or compiler == "gfortran":
        backend = f"CPU ({compiler})"
    else:
        gpu = "OpenACC" if compiler == "nvfortran" else "OpenMP offload"
        backend = f"FNL, {gpu} ({compiler})" if "fnl" in name else f"GPU, {gpu} ({compiler})"
    # `omp` is a variant (CPU threads) only outside the `omp-amd` backend marker
    variants = [v for v in VARIANTS if re.search(rf"-{v}(?!-amd)(-|$)", name)]
    return Mode(name=name, group=group, backend=backend, compiler=compiler, variants=variants)


def needs_varset(mode: Mode) -> str:
    """Return the varset a mode needs on the command line, or an empty string."""
    if mode.compiler == "nvfortran":
        return "NVF"
    if mode.compiler == "amdflang":
        return "AMD"
    return ""


def table(modes: list[Mode]) -> list[str]:
    """Return the Markdown table of a group of modes."""
    rows = ["| Mode | Backend | Variant | Varset |", "|------|---------|---------|--------|"]
    for m in modes:
        variant = ", ".join(VARIANTS[v] for v in m.variants) or "—"
        varset = needs_varset(m) or "default"
        rows.append(f"| `{m.name}` | {m.backend} | {variant} | {varset} |")
    return rows


def page(modes: list[Mode]) -> str:
    """Return the whole page."""
    lines = [
        "<!-- Generated by scripts/make_build_modes_page.py from `fobis build --lmodes`: do not edit by hand. -->",
        "",
        "# Build modes",
        "",
        f"The fobos files define {len(modes)} modes. Build one with `fobis build --mode <mode>`; the executables go "
        "to `exe/`.",
        "",
        "- **Varsets.** A varset selects the machine and toolchain: the HDF5 build (`$HDF5_PREFIX`) and, for "
        "nvfortran, the GPU compute capability (`$NVF_CC`). The default varset is `local_gnu`. Every nvfortran mode "
        "needs `--varset` with an NVF varset, or `-gpu=$NVF_CC` stays unexpanded and the first nvfortran call fails. "
        "The varset table is on the [install page](/start/install#varsets-one-per-machine-and-toolchain). In the "
        "tables, **default** is `local_gnu` (or the machine's GNU varset: `ci_gnu`, `iac_gnu`); **NVF** is a varset "
        "that sets `$NVF_CC` (`local_nvf`, `iac_nvf`, `leonardo`, `spacehpc`); **AMD** is a varset that sets the "
        "amdflang HDF5 (`local_amd`, `thera_amd`), combined with a `gfx*` varset to change `$GPU_ARCH` from its "
        "default, gfx942.",
        "- **Names.** `<target>-<backend>-<compiler>[-<variant>]`: `cpu` is the CPU backend (MPI, optionally "
        "OpenMP), `fnl` the GPU backend (OpenACC with `nvf`, OpenMP offload with `omp-amd`). Build clean after "
        "switching compiler: `.mod` files work only with the compiler that wrote them.",
        "- **Status.** Only FLUME and PRISM (and RIPPLE, the tutorial app) are maintained against the current library.",
        "",
    ]
    order = [APPS[a][0] for a in APPS] + ["Library", "Tests", "Benchmarks"]
    for group in order:
        members = [m for m in modes if m.group == group]
        if not members:
            continue
        status = next((s for name, s in APPS.values() if name == group), "")
        lines += [f"## {group}", ""]
        if status:
            lines += [f"Status: {status}.", ""]
        lines += table(members) + [""]
    return "\n".join(lines)


def main() -> None:
    """Parse the arguments and write the page."""
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--fobos", type=Path, default=ROOT / "fobos", help="fobos file (default: the repository's)")
    parser.add_argument("--out", type=Path, default=ROOT / "docs" / "reference" / "build-modes.md", help="page")
    args = parser.parse_args()
    modes = [classify(name) for name in list_modes(args.fobos)]
    if not modes:
        raise SystemExit("make_build_modes_page: fobis listed no mode")
    # every app/test include in fobos is optional (`?`): a missing one is skipped silently, so check that each group
    # the page documents is present rather than writing a shorter page
    missing = sorted({group for group, _ in APPS.values()} - {mode.group for mode in modes})
    if missing:
        raise SystemExit(f"make_build_modes_page: no mode listed for {', '.join(missing)} (a fobos include is missing)")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(page(modes))
    print(f"wrote {args.out} ({len(modes)} modes)")


if __name__ == "__main__":
    main()
